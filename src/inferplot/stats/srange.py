"""Accurate upper tail of the studentized range distribution, P(Q_{k,nu} > q).

Used for Games-Howell p-values (DECISIONS.md D31; R reference ``ptukey(q, k, df,
lower.tail = FALSE)``, whose far-tail error inferplot deliberately does not copy).
Only NumPy and SciPy.

Definitions
-----------
Let Z_1, ..., Z_k be independent N(0, 1), W = max Z_i - min Z_i their range, and
S = chi_nu / sqrt(nu) independent of W. The studentized range is Q = W / S, so

    P(Q > q) = integral_0^inf f_S(s) P(W > q s) ds                            (1)

(Student 1927; Newman 1939; the form evaluated by Lund & Lund 1983, Algorithm AS 190,
Applied Statistics 32: 204-210, and by Copenhaver & Holland 1988, J. Statist. Comput.
Simul. 30: 1-15). For nu = inf, S = 1 and P(Q > q) = P(W > q).

Range of k normals (Hartley 1942, Biometrika 32: 334-348; conditioning on the
minimum z, the other k - 1 values lie above z, and the range stays below w when they
all lie in (z, z + w)):

    P(W > w) = k integral phi(z) [a(z)^m - (a(z) - b(z))^m] dz,  m = k - 1,     (2)
    a(z) = P(Z > z),  b(z) = P(Z > z + w).

Why not ``1 - cdf``: both R's ptukey and SciPy's ``studentized_range.sf`` lose
accuracy in the far upper tail because some step subtracts nearly equal numbers.
Here the bracket in (2) is written as

    a^m - (a - b)^m = a^m (1 - r^m),   r = 1 - b / a = (a - b) / a in [0, 1),

and both logarithms are taken without cancellation:

    log r         = log1mexp(log b - log a),
    log(1 - r^m)  = log1mexp(m log r),

where log1mexp(x) = log(1 - e^x) for x <= 0 is evaluated as log(-expm1(x)) for
x > -log 2 and log1p(-exp(x)) otherwise (the standard switch; see M. Maechler,
"Accurately computing log(1 - exp(-|a|))", Rmpfr package vignette, 2012). log a and
log b come from ``scipy.special.log_ndtr``, which keeps full relative accuracy far
into both tails. Every quantity summed is positive, so the result has relative
accuracy near machine precision from tails near 1 down to the double underflow range.
In the far tail (b / a < e^-40) the factor is m b / a to relative 2e-16 * m, which
avoids an underflow of b / a in exp(log b - log a).

Quadrature
----------
Both integrands are smooth, positive and decay at least exponentially, so the
trapezoidal rule on the whole line converges geometrically (Trefethen & Weideman 2014,
"The exponentially convergent trapezoidal rule", SIAM Review 56: 385-458). All nodes
are summed in log space (log-sum-exp), so nothing under- or overflows.

* Inner integral (2): z = u - w / 2, so the peak sits near u = 0 when w is large and
  near the minimum's typical location, -sqrt(2 log k), when w is small. Nodes run
  from -sqrt(2 log k) - 10 to 10 with step min(0.2, 0.32 / sqrt(2 log k)) (the
  Gumbel-like scale of the minimum): 107 nodes for k = 2, 220 for k = 100.
* Outer integral (1): t = log s, so with x = nu / 2

      log f_T(t) = log 2 + (1/2) log(x / (2 pi)) - stirlerr(x) - x (e^(2t) - 1 - 2t),

  where stirlerr(x) = log Gamma(x) - (x - 1/2) log x + x - (1/2) log(2 pi) comes from
  the Stirling series for x >= 15 (Abramowitz & Stegun 6.1.41) and e^y - 1 - y from
  its Taylor series for |y| < 1, so no large terms cancel even for nu = 1e12. Step
  h = min(0.09, 0.18 / sqrt(2 log k), 0.55 / sqrt(2 nu)): the last term follows the
  width of f_T, the second the width in t over which P(W_k > q e^t) falls from 1 to
  0, which narrows as k grows. Nodes are centred at t_c = (1/2) log(nu / (nu + q^2/2))
  (the peak when P(W > w) ~ exp(-w^2 / 4)) and extended in blocks on each side until
  the log-integrand is 40 below its maximum (e^-40 = 4e-18).

Step and range were set by a convergence study during development: halving every step
and widening every range changes no result by more than one unit in the last place of
log P, for k = 2, 3, 5, 10, 50, 100, 200, nu from 1 to 1e9 and inf, and tails from
0.999 to 1e-300. With the earlier fixed outer step of 0.11 the error reached 3e-10
for k = 50 and 5e-7 for k = 200 at small nu.

Accuracy
--------
``tests/stats/test_srange.py`` compares with high-precision mpmath references frozen
in ``tests/data/studentized_range_reference.json`` and regenerated by
``tools/reference/studentized_range_mpmath.py``: the exact k = 2 identity
P(Q_{2,nu} > q) = P(|T_nu| > q / sqrt 2); the cancelling textbook form at
44 + |log10 P| digits for nu = inf; nested Gauss-Legendre quadrature for finite nu.
Tolerance ``studentized_range_tail`` in ``tests/tolerances.py``. Measured relative
error over all 792 reference points (k = 2..100, nu = 1..1e12 and inf), the same at
SciPy 1.11.1 and 1.18.1: at most 7.3e-15 for P >= 1e-15, 4.5e-14 for
P >= 1e-100 and 1.4e-13 at P = 1e-300, about |log P| x 2.2e-16, the rounding of
exp(log P); 2.9e-15 on the 31 Games-Howell pairs of the Phase 0 fixtures and
5.2e-15 on the 78 pairs (42 distinct points) of the later completed ggstatsplot
1.1.4 fixtures. Three more references cover the pairs of the fixture where
ggstatsplot fails (edge_n2, k = 3, Welch df 1.06 to 1.42, where R's ptukey returns
NaN): 1.2e-16.

R's ptukey is no reference: on the oracle's probe grid it is off by far more than
this function (``srange_sf``, "R's ptukey").
"""

from __future__ import annotations

import math
import operator
from typing import Final

import numpy as np
from numpy.typing import NDArray
from scipy import special

FloatArray = NDArray[np.float64]

__all__ = [
    "log_scaled_chi_density",
    "srange_logsf",
    "srange_sf",
    "stirlerr",
    "stirlerr_large",
]

_LN2: Final = math.log(2.0)
_LOG_SQRT_2PI: Final = 0.5 * math.log(2.0 * math.pi)
# b / a below e^_FAR_TAIL_X: 1 - (1 - b/a)^m = m b/a (1 + O(m b/a)), relative 4e-18 m.
_FAR_TAIL_X: Final = -40.0
# The outer integrand is followed until it is this far (in log units) below its peak.
_DROP: Final = 40.0
# Outer trapezoid step: min(_OUTER_H_CAP, _OUTER_H_K / sqrt(2 log k),
# _OUTER_H_REL * sigma) with sigma = 1 / sqrt(2 nu).
_OUTER_H_CAP: Final = 0.09
_OUTER_H_K: Final = 0.18
_OUTER_H_REL: Final = 0.55
_OUTER_BLOCK: Final = 24
# Inner trapezoid: step min(_INNER_H_CAP, _INNER_H_REL / sqrt(2 log k)); u runs from
# _INNER_PAD below the minimum's typical location, -sqrt(2 log k), to +_INNER_PAD.
_INNER_H_CAP: Final = 0.2
_INNER_H_REL: Final = 0.32
_INNER_PAD: Final = 10.0
# Stirling series coefficients of 1/x, 1/x^3, ..., 1/x^13 (Abramowitz & Stegun 6.1.41).
_STIRLING: Final = (
    1.0 / 12.0,
    -1.0 / 360.0,
    1.0 / 1260.0,
    -1.0 / 1680.0,
    1.0 / 1188.0,
    -691.0 / 360360.0,
    1.0 / 156.0,
)


def _log_ndtr(x: FloatArray) -> FloatArray:
    """log Phi(x), accurate in both tails (SciPy's ufunc, typed)."""
    return special.log_ndtr(x)


def _logsumexp(a: FloatArray) -> FloatArray:
    """log(sum(exp(a))) over the last axis; -inf where every term is -inf."""
    peak = a.max(axis=-1, keepdims=True)
    peak[~np.isfinite(peak)] = 0.0
    with np.errstate(divide="ignore"):
        return np.log(np.exp(a - peak).sum(axis=-1)) + peak[..., 0]


def _log1mexp(x: FloatArray) -> FloatArray:
    """log(1 - exp(x)) for x <= 0, without cancellation (-inf at x = 0).

    log(-expm1(x)) for x > -log 2, log1p(-exp(x)) otherwise (Maechler 2012).
    """
    with np.errstate(divide="ignore", invalid="ignore"):
        out = np.log1p(-np.exp(x))
        near = x > -_LN2
        out[near] = np.log(-np.expm1(x[near]))
    return out


def _inner_grid(k: int) -> tuple[FloatArray, float]:
    """Trapezoid nodes u and step for the inner integral (2), z = u - w / 2.

    The minimum of k normals sits near -sqrt(2 log k) with a Gumbel-like profile of
    scale about 1 / sqrt(2 log k); the step shrinks with that scale. The interval
    covers the peak for every w with at least 40 log units to spare on each side.
    """
    spread = math.sqrt(2.0 * math.log(k))
    h = min(_INNER_H_CAP, _INNER_H_REL / spread)
    lo = -spread - _INNER_PAD
    hi = _INNER_PAD
    n = math.ceil((hi - lo) / h)
    return lo + h * np.arange(n + 1, dtype=np.float64), h


def _log_range_sf(w: FloatArray, k: int) -> FloatArray:
    """log P(W_k > w) for the range W_k of k standard normals, elementwise in w >= 0."""
    u, h = _inner_grid(k)
    m = k - 1
    z = u[None, :] - 0.5 * w[:, None]
    with np.errstate(invalid="ignore", over="ignore"):
        log_a = _log_ndtr(-z)
        log_b_arg = -(z + w[:, None])
    log_b = _log_ndtr(log_b_arg)
    x = np.minimum(log_b - log_a, 0.0)  # log(b / a); rounding can make it > 0
    # over: 0.5 z^2 overflows only for w above ~1e154, where the term is -inf anyway.
    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        log_bracket = _log1mexp(m * _log1mexp(x))  # log(1 - r^m)
        far = x < _FAR_TAIL_X
        log_bracket[far] = math.log(m) + x[far]
        log_f = math.log(k) - _LOG_SQRT_2PI - 0.5 * z * z + m * log_a + log_bracket
        out = np.minimum(_logsumexp(log_f) + math.log(h), 0.0)
    # P(W > 0) = 1 exactly (the trapezoid sum is 1 to rounding); P(W > inf) = 0.
    out[w <= 0.0] = 0.0
    out[np.isinf(w)] = -np.inf
    return out


def stirlerr(x: float) -> float:
    """log Gamma(x) - (x - 1/2) log x + x - log sqrt(2 pi), the Stirling remainder."""
    if x >= 15.0:
        # Abramowitz & Stegun 6.1.41 through x^-13; the first omitted term,
        # 3617 / (122400 x^15), is below 7e-20 for x >= 15.
        x2 = 1.0 / (x * x)
        acc = 0.0
        for c in reversed(_STIRLING):
            acc = acc * x2 + c
        return acc / x
    # Below 15 the terms are at most |log Gamma(15)| = 25.2: absolute error ~6e-15.
    return math.lgamma(x) - (x - 0.5) * math.log(x) + x - _LOG_SQRT_2PI


def stirlerr_large(x: FloatArray) -> FloatArray:
    """``stirlerr`` element-wise for x >= 15 (the series branch, vectorized)."""
    if bool((x < 15.0).any()):
        raise ValueError("stirlerr_large needs x >= 15")
    inv = 1.0 / x
    x2 = inv * inv  # not 1 / (x * x), which overflows for x above 1.3e154
    acc = np.zeros_like(x)
    for c in reversed(_STIRLING):
        acc = acc * x2 + c
    return acc * inv


def expm1_minus_x(y: FloatArray) -> FloatArray:
    """e^y - 1 - y without cancellation near y = 0."""
    out = np.expm1(y) - y
    small = np.abs(y) < 1.0
    if bool(small.any()):
        ys = y[small]
        # Taylor series sum_{n >= 2} y^n / n!, Horner form; 18 terms give < 1e-19.
        acc = np.zeros_like(ys)
        for n in range(19, 1, -1):
            acc = (acc + 1.0) * ys / n
        out[small] = acc * ys
    return out


def log_scaled_chi_density(t: FloatArray, nu: float) -> FloatArray:
    """log density of T = log(chi_nu / sqrt(nu)) at t (finite nu > 0).

    With x = nu / 2 the density of S = chi_nu / sqrt(nu) is
    2 x^x s^(2x - 1) e^(-x s^2) / Gamma(x); in t = log s, and with Stirling's
    remainder, log f_T(t) = log 2 + (1/2) log(x / (2 pi)) - stirlerr(x)
    - x (e^(2t) - 1 - 2t), which keeps full accuracy for nu up to 1e12.
    """
    x = 0.5 * nu
    const = _LN2 + 0.5 * math.log(x / (2.0 * math.pi)) - stirlerr(x)
    return const - x * expm1_minus_x(2.0 * t)


def _check(q: float, k: int, df: float) -> None:
    if k < 2:
        raise ValueError(f"k must be an integer >= 2, got {k!r}")
    if math.isnan(q):
        raise ValueError("q must not be NaN")
    if math.isnan(df) or df <= 0.0:
        raise ValueError(f"df must be > 0 (inf for the normal range), got {df!r}")


def srange_logsf(q: float, k: int, df: float) -> float:
    """Natural log of P(Q_{k,df} > q), the studentized range upper tail.

    Accurate to about 1e-13 relative in P (absolute in the log) for k = 2..100,
    df in [1, inf] and every q >= 0, including tails far below the double underflow
    range, where ``srange_sf`` returns 0. ``df = inf`` gives the range of k standard
    normals. q <= 0 gives 0.0 (P = 1).
    """
    q, df, k = float(q), float(df), operator.index(k)
    _check(q, k, df)
    if q <= 0.0:
        return 0.0
    if math.isinf(q):
        return -math.inf
    if math.isinf(df):
        return float(_log_range_sf(np.array([q]), k)[0])

    sigma = 1.0 / math.sqrt(2.0 * df)
    # P(W_k > q e^t) falls from 1 to 0 over a range of t that narrows as k grows
    # (relative spread of the range); the step follows it.
    h = min(
        _OUTER_H_CAP, _OUTER_H_K / math.sqrt(2.0 * math.log(k)), _OUTER_H_REL * sigma
    )
    # log(df + q^2 / 2) without overflow for q up to the largest double
    centre = 0.5 * (
        math.log(df) - float(np.logaddexp(math.log(df), 2.0 * math.log(q) - _LN2))
    )

    def block(j0: int, j1: int) -> FloatArray:
        t = centre + h * np.arange(j0, j1, dtype=np.float64)
        return log_scaled_chi_density(t, df) + _log_range_sf(q * np.exp(t), k)

    first = math.ceil(12.0 * sigma / h) + 1
    lo, hi = -first, first + 1
    parts = [block(lo, hi)]
    peak = float(np.max(parts[0]))
    # Extend left, then right, until the integrand is _DROP below the peak.
    while parts[0][0] > peak - _DROP:
        parts.insert(0, block(lo - _OUTER_BLOCK, lo))
        lo -= _OUTER_BLOCK
        peak = max(peak, float(np.max(parts[0])))
    while parts[-1][-1] > peak - _DROP:
        parts.append(block(hi, hi + _OUTER_BLOCK))
        hi += _OUTER_BLOCK
        peak = max(peak, float(np.max(parts[-1])))
    sums = np.array([float(_logsumexp(part)) for part in parts])
    return min(0.0, float(_logsumexp(sums)) + math.log(h))


def srange_sf(q: float, k: int, df: float) -> float:
    """P(Q_{k,df} > q): upper tail of the studentized range for k means, df error df.

    ``df = math.inf`` gives the range of k standard normals. Relative accuracy about
    1e-13 wherever the result is a normal double (module docstring, "Accuracy").

    R's ptukey
    ----------
    The quantity R computes as ``ptukey(q, k, df, lower.tail = FALSE)``, whose
    errors this function does not reproduce (DECISIONS.md D31). On the oracle probe
    grid (probe-ptukey, section "tails": k = 2, 3, 4, 5, 6, 10, 20; q = 1 to 30;
    1,365 points; tests/stats/test_probes.py) the largest absolute difference
    between R's value and this function is, by df: 1.35e-3 at df 2, 3.2e-5 at
    df 5, 1.8e-7 at df 10, at most 1.9e-8 for df 20 to 1000 and at df = inf,
    5.3e-7 at df 25000, and 1.9e-5 at df 1e5, where R returns its infinite-df
    value; at df 1 and 1.5 R returns NaN for every point. These are R's errors:
    this function's accuracy is measured against the mpmath references (module
    docstring), which reach df 1000 for k >= 3 and df 1e12 for k = 2; between
    df 1000 and inf for k >= 3 the evidence is the convergence study and checks
    such as this one: at k = 10 and q = 8 the tail falls as df grows, and
    R's own values at df 1000 and df = inf are 8.98e-7 and 6.89e-7, yet at
    df 25000 R returns 1.69e-7 (this function: 6.97e-7). In the Games-Howell
    pairs of the fixtures (gamesHowellTest's raw p, same probe) R is within
    2.8e-10 relative of this function for p >= 0.01 and 3.6e-7 for p >= 1e-4,
    but its absolute error reaches 4.7e-10 where the true tail is 7.5e-15 (iris
    setosa-versicolor).
    """
    return math.exp(srange_logsf(q, k, df))
